#!/usr/bin/env python3
"""Ternary standard-cell library L for the cost model and a
completeness check via Słupecki's criterion (all unary functions + a surjective,
essentially binary operation).

Values: 0 = '-' (logic 0 / low), 1 = '0' (logic 1 / mid), 2 = '+' (logic 2 / high).
Unary cells are represented as 2-input tables that ignore the right operand so the
same CP-SAT model handles them (their cost is the cell's cost; the dangling operand
is a modelling artefact and is not counted).

Transistor counts: placeholders to be filled from Lin, Kim & Lombardi, IEEE TNANO 10(2)
2011; the cost variants actually used are in data/cell_costs.json.
"""
import itertools

def un2(f):
    """lift a unary map f: {0,1,2}->{0,1,2} to a flat 3x3 table ignoring the right operand"""
    return [f[a] for a in range(3) for b in range(3)]

def bin2(f):
    return [f(a, b) for a in range(3) for b in range(3)]

STI = [2, 1, 0]   # standard ternary inverter: 2-x
NTI = [2, 0, 0]   # negative TI: 2 if x==0 else 0
PTI = [2, 2, 0]   # positive TI: 0 if x==2 else 2
TMIN = lambda a, b: min(a, b)
TMAX = lambda a, b: max(a, b)
TNAND = lambda a, b: 2 - min(a, b)
TNOR = lambda a, b: 2 - max(a, b)

# name -> (table, transistor cost placeholder)
INC = [1, 2, 0]   # successor x+1 (mod 3) — Etiemble's "succ" cell
DEC = [2, 0, 1]   # predecessor x-1 (mod 3) — "pred"
LIB_L = {
    "STI":  (un2(STI), None),
    "NTI":  (un2(NTI), None),
    "PTI":  (un2(PTI), None),
    "TNAND":(bin2(TNAND), None),
    "TNOR": (bin2(TNOR), None),
}

def unary_closure(tables):
    """all unary functions generated by composing the given 2-input tables (as functions of one variable)"""
    ident = (0, 1, 2)
    S = {ident}
    frontier = [ident]
    while frontier:
        new = []
        cur = list(S)
        for t in tables:
            for f in cur:
                for g in frontier:
                    for (p, q) in ((f, g), (g, f)):
                        h = tuple(t[p[x]*3 + q[x]] for x in range(3))
                        if h not in S:
                            S.add(h); new.append(h)
        frontier = new
    return S

def surjective(t): return set(t) == {0, 1, 2}
def essentially_binary(t):
    dep_x = any(t[a1*3+b] != t[a2*3+b] for b in range(3) for a1 in range(3) for a2 in range(3))
    dep_y = any(t[a*3+b1] != t[a*3+b2] for a in range(3) for b1 in range(3) for b2 in range(3))
    return dep_x and dep_y

def slupecki_complete(tables):
    U = unary_closure(tables)
    ess = [t for t in tables if surjective(t) and essentially_binary(t)]
    return len(U) == 27, len(U), len(ess) > 0

if __name__ == "__main__":
    tabs = [v[0] for v in LIB_L.values()]
    ok, nU, ess = slupecki_complete(tabs)
    print(f"L = {list(LIB_L)}: unary functions generated = {nU}/27, has surjective essentially-binary op = {ess} -> complete: {ok and ess}")
    # subsets: which minimal sub-libraries are complete?
    names = list(LIB_L)
    for r in range(1, len(names)+1):
        for sub in itertools.combinations(names, r):
            ok, nU, ess = slupecki_complete([LIB_L[n][0] for n in sub])
            if ok and ess:
                print("  complete subset:", sub)
